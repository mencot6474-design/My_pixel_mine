export type ChibiAnimState = 'idle' | 'dash' | 'attack' | 'aura';

export type ChibiRarity =
  | 'common'
  | 'uncommon'
  | 'rare'
  | 'epic'
  | 'legendary'
  | 'rainbow'
  | 'mythic'
  | 'exotic'
  | 'secret'
  | 'fusion'
  | 'limited'
  | 'twin'
  | 'omega'
  | 'anomaly';

export interface ChibiPoseUrls {
  idle: string;
  walk: string;
  attack: string;
  pose: string;
}

export interface ChibiDef {
  id: string;
  name: string;
  spriteUrl: string;
  poses: ChibiPoseUrls;
  frames: number;
  rarity: ChibiRarity;
  accentColor: string;
  baseDps: number;
  poseScale?: number;
  smoothFilter?: boolean;
  walkFacesLeft?: boolean;
}

